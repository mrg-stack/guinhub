import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const sources = await Promise.all(['index.html', 'portal.js'].map(file => readFile(new URL(file, root), 'utf8')));
const names = [...new Set(sources.flatMap(source =>
  [...source.matchAll(/\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)].map(match => match[1])
))].sort();
const base = 'https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.1/';
const rules = [];
for (const name of names) {
  const response = await fetch(`${base}icons/${name}.svg`);
  if (!response.ok) throw new Error(`Unable to download ${name}: HTTP ${response.status}`);
  const svg = (await response.text()).trim();
  if (!svg.startsWith('<svg')) throw new Error(`Invalid SVG for ${name}`);
  const uri = `data:image/svg+xml,${encodeURIComponent(svg)}`;
  rules.push(`.bi-${name}::before { --icon: url("${uri}"); }`);
}
const licenseResponse = await fetch(`${base}LICENSE`);
if (!licenseResponse.ok) throw new Error(`Unable to download icon license: HTTP ${licenseResponse.status}`);
const license = await licenseResponse.text();
const css = `/* Generated by node scripts/build-icons.mjs. Bootstrap Icons 1.11.1, MIT; see bootstrap-icons-LICENSE.txt. */
.bi::before {
  display: inline-block;
  width: 1em;
  height: 1em;
  background-color: currentColor;
  -webkit-mask: var(--icon) center / contain no-repeat;
  mask: var(--icon) center / contain no-repeat;
  vertical-align: -0.125em;
  content: "";
}
${rules.join('\n')}
`;
await writeFile(new URL('assets/icons.css', root), css);
await writeFile(new URL('assets/bootstrap-icons-LICENSE.txt', root), license);
console.log(`Generated ${names.length} icons in ${fileURLToPath(new URL('assets/icons.css', root))} (${Buffer.byteLength(css)} bytes).`);
